/** 持久分区补丁的等长前后文（各 37 字节）。 */
const PATCH_BEFORE = '`dsh-sidebar-browser-${randomUUID()}`'
const PATCH_AFTER = '"persist:"+workspace.replace(/:/g,"")'

/** app.asar 路径：环境变量优先，其次从宿主可执行文件推断，最后用默认安装位置。 */
export function resolveAsarPath() {
  const fs = rawFs()
  const candidates = []
  if (typeof process.env.DSH_ASAR === 'string' && process.env.DSH_ASAR !== '') candidates.push(process.env.DSH_ASAR)
  try {
    if (typeof process.execPath === 'string' && process.execPath !== '') {
      candidates.push(join(dirname(process.execPath), 'resources', 'app.asar'))
    }
  } catch (error) {
    // 推断失败就走默认位置。
  }
  candidates.push(join('D:\\Program Files', 'DeepSeek Harness', 'resources', 'app.asar'))
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) return candidate
  }
  return candidates[candidates.length - 1]
}

/** 补丁状态的缓存，避免每次点开页面都读 180MB 的归档。 */
let patchCache = { key: '', value: null }

/**
 * 读 app.asar，判断持久分区补丁是否在位。
 * @returns 状态对象；读不了时带 error。
 */
export function readPatchState() {
  const file = resolveAsarPath()
  const fs = rawFs()
  try {
    const stat = fs.statSync(file)
    const key = `${file}|${stat.size}|${stat.mtimeMs}`
    if (patchCache.key === key && patchCache.value !== null) return patchCache.value
    const bytes = fs.readFileSync(file)
    const hasOld = bytes.indexOf(PATCH_BEFORE) !== -1
    const hasNew = bytes.indexOf(PATCH_AFTER) !== -1
    let writable = false
    try {
      const probe = fs.openSync(file, 'r+')
      fs.closeSync(probe)
      writable = true
    } catch (error) {
      writable = false
    }
    const value = {
      asar: file,
      size: bytes.length,
      patched: hasNew && !hasOld,
      needsPatch: hasOld && !hasNew,
      writable,
      hasOld,
      hasNew,
    }
    patchCache = { key, value }
    return value
  } catch (error) {
    return { asar: file, patched: false, needsPatch: false, writable: false, error: messageOf(error) }
  }
}

/** PowerShell 单引号字符串转义。 */
function psQuote(text) {
  return `'${String(text).replace(/'/g, "''")}'`
}

/**
 * 生成提权后执行的补丁脚本（纯 ASCII，避免 PowerShell 5.1 的编码坑）。
 * 脚本会：请求关闭 DSH → 等归档可写 → 等长替换 → 回读校验 → 重新启动。
 */
function buildPatchHelper(asar, installDir) {
  const log = join(tmpdir(), 'dsh-persist-patch.log')
  const lines = [
    '# auto-generated by @local/dsh-webchat-right',
    "$ErrorActionPreference = 'Stop'",
    `$Asar = ${psQuote(asar)}`,
    `$InstallDir = ${psQuote(installDir)}`,
    `$Log = ${psQuote(log)}`,
    'function Say($t) { $line = (Get-Date -Format "HH:mm:ss") + " " + $t; $line | Out-File -LiteralPath $Log -Append -Encoding UTF8; Write-Host $line }',
    `$Before = ${psQuote(PATCH_BEFORE)}`,
    `$After = ${psQuote(PATCH_AFTER)}`,
    'function Find-All($Haystack, $Needle) {',
    '  $hits = New-Object System.Collections.Generic.List[int]',
    '  $n = $Needle.Length',
    '  $limit = $Haystack.Length - $n',
    '  for ($i = 0; $i -le $limit; $i++) {',
    '    if ($Haystack[$i] -ne $Needle[0]) { continue }',
    '    $ok = $true',
    '    for ($j = 1; $j -lt $n; $j++) { if ($Haystack[$i + $j] -ne $Needle[$j]) { $ok = $false; break } }',
    '    if ($ok) { $hits.Add($i); $i += $n - 1 }',
    '  }',
    '  return $hits',
    '}',
    'try {',
    '  Say "start"',
    "  $proc = Get-Process -Name 'DeepSeek Harness' -ErrorAction SilentlyContinue",
    '  if ($proc) {',
    '    foreach ($p in $proc) { [void]$p.CloseMainWindow() }',
    '    Say "close requested"',
    '    for ($i = 0; $i -lt 15; $i++) { Start-Sleep -Seconds 1; if (-not (Get-Process -Name "DeepSeek Harness" -ErrorAction SilentlyContinue)) { break } }',
    '    $left = Get-Process -Name "DeepSeek Harness" -ErrorAction SilentlyContinue',
    '    if ($left) { Say "still running; forcing exit"; $left | Stop-Process -Force -ErrorAction SilentlyContinue; Start-Sleep -Seconds 3 }',
    '  }',
    '  $writable = $false',
    '  for ($i = 0; $i -lt 90; $i++) {',
    "    try { $fs = [IO.File]::Open($Asar, 'Open', 'ReadWrite', 'None'); $fs.Close(); $writable = $true; break } catch { Start-Sleep -Seconds 1 }",
    '  }',
    '  if (-not $writable) { Say "asar is locked; abort"; exit 3 }',
    '  $bytes = [IO.File]::ReadAllBytes($Asar)',
    '  $b = [Text.Encoding]::UTF8.GetBytes($Before)',
    '  $a = [Text.Encoding]::UTF8.GetBytes($After)',
    '  $hits = Find-All $bytes $b',
    '  Say ("before=" + $b.Length + " after=" + $a.Length + " hits=" + $hits.Count)',
    '  if ($b.Length -ne $a.Length -or $hits.Count -ne 1) { Say "refusing to write"; exit 2 }',
    '  $backup = $Asar + ".orig-bak"',
    '  Copy-Item -LiteralPath $Asar -Destination $backup -Force',
    '  Say "backup written (current version)"',
    '  foreach ($offset in $hits) { for ($k = 0; $k -lt $a.Length; $k++) { $bytes[$offset + $k] = $a[$k] } }',
    '  [IO.File]::WriteAllBytes($Asar, $bytes)',
    '  $check = [IO.File]::ReadAllBytes($Asar)',
    '  $old = Find-All $check $b',
    '  $new = Find-All $check $a',
    '  Say ("verify old=" + $old.Count + " new=" + $new.Count)',
    "  if ($new.Count -ne 1 -or $old.Count -ne 0) { Say 'verification failed'; exit 4 }",
    "  Say 'PATCH OK'",
    '} catch {',
    '  Say ("error: " + $_.Exception.Message)',
    '} finally {',
    '  $exe = Get-ChildItem -LiteralPath $InstallDir -Filter *.exe -ErrorAction SilentlyContinue | Select-Object -First 1',
    '  if ($exe) { Say ("relaunch " + $exe.FullName); Start-Process -FilePath $exe.FullName | Out-Null } else { Say "no exe found to relaunch" }',
    '}',
  ]
  return { text: lines.join('\r\n'), log }
}

/**
 * 用 UAC 提权运行补丁脚本。
 *
 * 不直接 `Start-Process -Verb RunAs`：从隐藏窗口的 `-Command` 里提权可能
 * 静默失败且没有任何痕迹。这里改为先写一个带日志的启动器脚本，再由它提权，
 * 成功与失败都会落到 `*-launch.log`，宿主把结果回给界面。
 * @returns 相关路径，供调用方等待并读取启动日志。
 */
export function launchPatchHelper() {
  const asar = resolveAsarPath()
  const installDir = dirname(dirname(asar))
  const helper = buildPatchHelper(asar, installDir)
  const stamp = Date.now()
  const helperFile = join(tmpdir(), `dsh-persist-patch-${stamp}.ps1`)
  const launcherFile = join(tmpdir(), `dsh-persist-patch-${stamp}-launch.ps1`)
  const launchLog = join(tmpdir(), `dsh-persist-patch-${stamp}-launch.log`)
  writeFileSync(helperFile, `${helper.text}\r\n`, 'utf8')

  const launcher = [
    "# auto-generated launcher",
    "$ErrorActionPreference = 'Stop'",
    `$Log = ${psQuote(launchLog)}`,
    'function Say($t) { $line = (Get-Date -Format "HH:mm:ss") + " " + $t; $line | Out-File -LiteralPath $Log -Append -Encoding UTF8 }',
    "Say 'launcher start'",
    'try {',
    `  Start-Process -FilePath 'powershell.exe' -Verb RunAs -ArgumentList @('-NoProfile','-ExecutionPolicy','Bypass','-File',${psQuote(helperFile)}) -ErrorAction Stop`,
    "  Say 'uac requested'",
    '} catch {',
    '  Say ("error: " + $_.Exception.Message)',
    '}',
  ].join('\r\n')
  writeFileSync(launcherFile, `${launcher}\r\n`, 'utf8')

  const child = spawn('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', launcherFile], {
    detached: true,
    stdio: 'ignore',
    windowsHide: false,
  })
  child.unref()
  return { helper: helperFile, launcher: launcherFile, log: launchLog, helperLog: helper.log }
}

/** 展开 `~` 前缀。 */
function expandHome(path) {
  if (path === '~') return homedir()
  if (path.startsWith('~/') || path.startsWith('~\\')) return join(homedir(), path.slice(2))
  return path
}

/**
 * dsh 的用户数据根：`$DSH_HOME` 非空时用它，否则 `~/.dsh`。
 * 空字符串按未设置处理，避免解析成当前目录。
 */
export function dshHome(env = process.env) {
  const fromEnv = env.DSH_HOME
  const override = fromEnv !== undefined && fromEnv.trim().length > 0 ? expandHome(fromEnv) : undefined
  return resolve(override ?? join(homedir(), '.dsh'))
}

/** 与上游一致的快照路径，保证登录连续。 */
export function sessionFile() {
  return join(dshHome(), 'dsh-webchat', 'session.json')
}

/** 只认 DeepSeek 的 cookie，授权站点的 cookie 不进快照。 */
function isDeepSeekCookie(cookie) {
  if (cookie === null || typeof cookie !== 'object' || typeof cookie.domain !== 'string') return false
  const domain = cookie.domain.replace(/^\./, '').toLowerCase()
  return domain === 'deepseek.com' || domain.endsWith('.deepseek.com')
}

/** 桌面壳签发给浏览器访客的分区名，别的分区一概不碰。 */
// 默认是内存分区 dsh-sidebar-browser-<uuid>；打了持久化补丁后是 persist:<name>。
const GUEST_PARTITION = /^(?:dsh-sidebar-browser-[0-9a-f-]{8,}|persist:.{1,200})$/

/** Electron 可达性，经 /state 报告一次。 */
let electronStatus = 'unknown'

/** 读 JSON 请求体；非法或超限读作 null。 */
function readJsonBody(req, limit = 2 * 1024 * 1024) {
  return new Promise((resolve) => {
    let size = 0
    const chunks = []
    req.on('data', (chunk) => {
      size += chunk.length
      if (size > limit) {
        req.destroy()
        resolve(null)
        return
      }
      chunks.push(chunk)
    })
    req.on('end', () => {
      try {
        resolve(JSON.parse(Buffer.concat(chunks).toString('utf8') || '{}'))
      } catch (error) {
        resolve(null)
      }
    })
    req.on('error', () => resolve(null))
  })
}

/** 读快照。 */
export function readSnapshot(file) {
  try {
    const parsed = JSON.parse(readFileSync(file, 'utf8'))
    if (parsed === null || typeof parsed !== 'object') return null
    return {
      cookies: Array.isArray(parsed.cookies) ? parsed.cookies : [],
      storage: Array.isArray(parsed.storage) ? parsed.storage : [],
      cookie: typeof parsed.cookie === 'string' ? parsed.cookie : '',
      savedAt: typeof parsed.savedAt === 'string' ? parsed.savedAt : '',
    }
  } catch (error) {
    return null
  }
}

/** 原子写快照，用户私有权限。 */
export function writeSnapshot(file, snapshot) {
  mkdirSync(dirname(file), { recursive: true })
  const temp = `${file}.tmp`
  writeFileSync(temp, `${JSON.stringify(snapshot, null, 2)}\n`, { mode: 0o600 })
  renameSync(temp, file)
}

/** 把快照里的 cookie 写到分区会话上。 */
export async function restoreCookies(cookies, snapshot) {
  let restored = 0
  for (const cookie of snapshot.cookies) {
    if (!isDeepSeekCookie(cookie)) continue
    if (typeof cookie.name !== 'string' || typeof cookie.value !== 'string') continue
    const domain = typeof cookie.domain === 'string' ? cookie.domain : ''
    if (domain === '') continue
    const path = typeof cookie.path === 'string' && cookie.path !== '' ? cookie.path : '/'
    const details = {
      url: `${cookie.secure === true ? 'https' : 'http'}://${domain.replace(/^\./, '')}${path}`,
      name: cookie.name,
      value: cookie.value,
      domain,
      path,
      secure: cookie.secure === true,
      httpOnly: cookie.httpOnly === true,
    }
    if (typeof cookie.expirationDate === 'number') details.expirationDate = cookie.expirationDate
    if (typeof cookie.sameSite === 'string') details.sameSite = cookie.sameSite
    try {
      await cookies.set(details)
      restored += 1
    } catch (error) {
      // 一个被拒绝的 cookie 不值得毁掉整次恢复。
    }
  }
  return restored
}

/** 序列化分区 cookie（含 HttpOnly）。 */
export async function captureCookies(cookies) {
  const list = await cookies.get({})
  return list.filter(isDeepSeekCookie).map((cookie) => ({
    name: cookie.name,
    value: cookie.value,
    domain: cookie.domain,
    path: cookie.path,
    secure: cookie.secure === true,
    httpOnly: cookie.httpOnly === true,
    ...(typeof cookie.expirationDate === 'number' ? { expirationDate: cookie.expirationDate } : {}),
    ...(typeof cookie.sameSite === 'string' ? { sameSite: cookie.sameSite } : {}),
  }))
}


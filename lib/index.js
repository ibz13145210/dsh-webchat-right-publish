/**
 * dsh-webchat-right — host half.
 *
 * 从 @jaychang1989/dsh-webchat 0.7.8 的宿主半边改写而来（Apache-2.0，见 NOTICE）。
 * 职责未变：
 *
 *   1. 登录跨重启：桌面端给每个浏览器访客的分区是进程级、随机命名的，
 *      cookie 随进程消失。只有 Electron 主进程能读一个分区的 cookie（含
 *      HttpOnly），所以这一半把 cookie 写盘、下次启动前写回；页面自己的
 *      localStorage 与 document.cookie 由浏览器半边搬运。
 *   2. 窗口降级：没有原生访客桥时（纯 `dsh web`），用系统浏览器打开。
 *   3. 外链：把站点弹的新窗口交给系统浏览器。
 *
 * 路由：GET /state、POST /open、POST /session/restore、POST /session/save、
 * POST /external。快照与上游同路径（~/.dsh/dsh-webchat/session.json），
 * 因此上游版本留下的登录可以直接沿用。
 */


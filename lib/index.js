/** Electron 的 CJS 入口：ESM 解析器未必把 `electron` 交给 Electron 自己的解析器。 */
const requireHere = createRequire(import.meta.url)

/**
 * 未打补丁的原生 fs。
 *
 * 宿主跑在 Electron 主进程里时，Electron 会把 `fs` 换成能读 asar 内部的版本；
 * 于是「读 app.asar 这个归档文件本身」会被当成「在归档里找文件」，报
 * `ENOENT, not found in <asar>`。读写归档必须绕开这层，用 Electron 的
 * `original-fs`；纯 Node 环境退回普通 fs。
 */
let rawFsModule = null
function rawFs() {
  if (rawFsModule !== null) return rawFsModule
  try {
    rawFsModule = requireHere('original-fs')
  } catch (error) {
    rawFsModule = requireHere('node:fs')
  }
  return rawFsModule
}

